-- =============================================================================
-- LOCALE HELPER FUNCTION (Default fallback: 'en')
-- =============================================================================
function _L(key)
    local lang = Config.Locale or 'en'
    if Locales[lang] and Locales[lang][key] then
        return Locales[lang][key]
    end
    if Locales['en'] and Locales['en'][key] then
        return Locales['en'][key]
    end
    return key
end
